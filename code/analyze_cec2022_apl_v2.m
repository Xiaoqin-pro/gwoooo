function report = analyze_cec2022_apl_v2(resultsCsv, outputDir)
%ANALYZE_CEC2022_APL_V2 Ranks and unadjusted Wilcoxon rank-sum screening.
if nargin < 1 || isempty(resultsCsv)
    resultsCsv=fullfile(gwo_project_root(),'results', ...
        'cec2022_apl_v2_6worker_dev','cec2022_development.csv');
end
if nargin < 2 || isempty(outputDir), outputDir=fileparts(resultsCsv); end
T=readtable(resultsCsv,'TextType','string');
optimum=[300 400 600 800 900 1800 2000 2200 2300 2400 2600 2700];
T.Error=max(T.BestFitness-optimum(T.Function)',0);
variants=["gwo","tournament","apl_v2","apl_weighted", ...
    "tournament_apl_v2","tournament_apl_weighted"];
funcs=unique(T.Function)'; dims=unique(T.Dimension)';
perFunction=table(); rankSum=zeros(numel(variants),1); winCount=zeros(numel(variants),1);
friedmanRows=cell(numel(funcs)*numel(dims),4); pidx=0;
for dim=dims
    for func=funcs
        pidx=pidx+1; means=nan(1,numel(variants)); samples=cell(1,numel(variants));
        for v=1:numel(variants)
            rows=T(T.Dimension==dim & T.Function==func & T.Variant==variants(v),:);
            [~,ord]=sort(rows.Seed); rows=rows(ord,:); samples{v}=rows.Error;
            means(v)=mean(rows.Error);
        end
        ranks=tiedrank(means); rankSum=rankSum+ranks'; winCount=winCount+(means==min(means))';
        perFunction=[perFunction; table(func,dim,means(1),means(2),means(3), ...
            means(4),means(5),means(6),ranks(1),ranks(2),ranks(3), ...
            ranks(4),ranks(5),ranks(6),'VariableNames', ...
            {'Function','Dimension','GWO_MeanError','Tournament_MeanError', ...
            'APLv2_MeanError','APLweighted_MeanError','TournamentAPL_MeanError', ...
            'TournamentAPLweighted_MeanError','GWO_Rank','Tournament_Rank', ...
            'APLv2_Rank','APLweighted_Rank','TournamentAPL_Rank', ...
            'TournamentAPLweighted_Rank'})]; %#ok<AGROW>
        X=zeros(numel(samples{1}),numel(variants));
        for v=1:numel(variants), X(:,v)=samples{v}; end
        p=friedman(X,1,'off');
        friedmanRows(pidx,:)={func,dim,p,variants(find(means==min(means),1))};
    end
end
overall=table(variants',rankSum/numel(funcs)/numel(dims),winCount, ...
    'VariableNames',{'Variant','AverageFunctionRank','BestMeanErrorCases'});

% Rank-sum comparisons are exploratory and intentionally unadjusted here.
comparisons={"apl_v2","gwo"; "apl_v2","tournament"; ...
    "apl_weighted","gwo"; "apl_weighted","tournament"; ...
    "tournament_apl_v2","gwo"; "tournament_apl_v2","tournament"; ...
    "tournament_apl_weighted","gwo"; "tournament_apl_weighted","tournament"; ...
    "apl_weighted","apl_v2"; "tournament_apl_v2","apl_v2"; ...
    "tournament_apl_weighted","apl_weighted"; ...
    "tournament_apl_weighted","tournament_apl_v2"};
pairRows=cell(numel(funcs)*numel(dims)*size(comparisons,1),9); q=0;
for c=1:size(comparisons,1)
    method=string(comparisons{c,1}); comparator=string(comparisons{c,2});
    for dim=dims
        for func=funcs
            q=q+1;
            a=T.Error(T.Function==func & T.Dimension==dim & T.Variant==method);
            z=T.Error(T.Function==func & T.Dimension==dim & T.Variant==comparator);
            p=ranksum(a,z);
            pairRows(q,:)={func,dim,method,comparator,numel(a), ...
                median(a)-median(z),sum(a<z),sum(a>z),p};
        end
    end
end
pairwise=cell2table(pairRows,'VariableNames', ...
    {'Function','Dimension','Method','Comparator','NPerGroup', ...
    'MedianErrorDifference','Wins','Losses','RankSumP_Unadjusted'});
pairwise.Method=string(pairwise.Method); pairwise.Comparator=string(pairwise.Comparator);
friedmanTable=cell2table(friedmanRows,'VariableNames', ...
    {'Function','Dimension','FriedmanP_Unadjusted','BestMeanVariant'});
friedmanTable.BestMeanVariant=string(friedmanTable.BestMeanVariant);

aplRows=table(); aplVariants=variants(3:end);
for v=1:numel(aplVariants)
    rows=T(T.Variant==aplVariants(v),:);
    aplRows=[aplRows; table(aplVariants(v),mean(rows.GatePassRate,'omitnan'), ...
        mean(rows.Pattern3Evaluations,'omitnan'),mean(rows.Pattern4Evaluations,'omitnan'), ...
        mean(rows.Pattern5Evaluations,'omitnan'),mean(rows.Pattern3Successes,'omitnan'), ...
        mean(rows.Pattern4Successes,'omitnan'),mean(rows.Pattern5Successes,'omitnan'), ...
        mean(rows.ArchiveSelections,'omitnan'),mean(rows.ArchiveSelectionRate,'omitnan'), ...
        mean(rows.DiversityInitial,'omitnan'),mean(rows.DiversityFinal,'omitnan'), ...
        mean(rows.DiversityMin,'omitnan'),'VariableNames', ...
        {'Variant','MeanGatePassRate','MeanPattern3Evaluations','MeanPattern4Evaluations', ...
        'MeanPattern5Evaluations','MeanPattern3Successes','MeanPattern4Successes', ...
        'MeanPattern5Successes','MeanArchiveSelections','MeanArchiveSelectionRate', ...
        'MeanInitialDiversity','MeanFinalDiversity','MeanMinimumDiversity'})]; %#ok<AGROW>
end
if ~exist(outputDir,'dir'), mkdir(outputDir); end
writetable(perFunction,fullfile(outputDir,'cec2022_apl_v2_per_function.csv'));
writetable(overall,fullfile(outputDir,'cec2022_apl_v2_algorithm_ranks.csv'));
writetable(pairwise,fullfile(outputDir,'cec2022_apl_v2_rank_sum_unadjusted.csv'));
writetable(friedmanTable,fullfile(outputDir,'cec2022_apl_v2_friedman_unadjusted.csv'));
writetable(aplRows,fullfile(outputDir,'cec2022_apl_v2_diagnostics.csv'));
report=struct('PerFunction',perFunction,'Overall',overall,'Pairwise',pairwise, ...
    'Friedman',friedmanTable,'Diagnostics',aplRows);
end
